#!/usr/bin/env python3
"""Compile the GPU helper's shaders (src/gpu/*.comp, the viewport's .vert and
.frag; GLSL) to SPIR-V with glslc and write src/gpu/spv.s: each module as
words in .rodata, spv_<name> .. spv_<name>_end. The output is committed, so
building the helper needs no shader compiler.

    python3 tools/genspv.py              all of them
    python3 tools/genspv.py viewv viewf  only these (the rest kept from spv.s)
"""
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GPU = os.path.join(HERE, '..', 'src', 'gpu')
# (name, source, defines, target): ptg is pt.comp with shader graphs; ptr and
# ptgr trace with ray queries (RTX, Vulkan 1.2); asprep feeds their builds;
# viewv, viewf draw the viewport (a source without an extension is a .comp)
SHADERS = [('pt', 'pt', [], '1.1'), ('raster', 'raster', [], '1.1'), ('ptg', 'pt', ['-DGRAPHS'], '1.1'),
           ('ptr', 'pt', ['-DRTX'], '1.2'), ('ptgr', 'pt', ['-DGRAPHS', '-DRTX'], '1.2'),
           ('asprep', 'asprep', [], '1.1'), ('viewv', 'view.vert', [], '1.1'), ('viewf', 'view.frag', [], '1.1')]


def kept():
    """spv.s's modules as they are: name -> its lines"""
    mods, name = {}, None
    path = os.path.join(GPU, 'spv.s')
    for line in open(path).read().splitlines() if os.path.exists(path) else []:
        if line.startswith('.globl spv_') and not line.endswith('_end'):
            name = line[len('.globl spv_'):]
            mods[name] = []
        if name:
            mods[name].append(line)
            if line == 'spv_%s_end:' % name:
                name = None
    return mods


def main():
    only = set(sys.argv[1:])
    old = kept() if only else {}
    out = ['# generated by tools/genspv.py from src/gpu/*.comp, *.vert, *.frag - do not edit',
           '.section .rodata', '.align 4']
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, defs, env in SHADERS:
            if only and name not in only:
                out.extend(old[name])
                continue
            spv = os.path.join(tmp, name + '.spv')
            if '.' not in src:
                src += '.comp'
            subprocess.run(['glslc', '-O', '--target-env=vulkan' + env] + defs + ['-o', spv,
                            os.path.join(GPU, src)], check=True)
            data = open(spv, 'rb').read()
            words = struct.unpack('<%dI' % (len(data) // 4), data)
            out.append('.globl spv_%s\n.globl spv_%s_end' % (name, name))
            out.append('spv_%s:' % name)
            for i in range(0, len(words), 8):
                out.append('    .long ' + ', '.join('0x%08x' % w for w in words[i:i + 8]))
            out.append('spv_%s_end:' % name)
            print('%s: %d bytes of SPIR-V' % (name, len(data)))
    with open(os.path.join(GPU, 'spv.s'), 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    sys.exit(main())
