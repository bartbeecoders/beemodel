#!/usr/bin/env python3
"""Compile the GPU helper's compute shaders (src/gpu/*.comp, GLSL) to SPIR-V
with glslc and write src/gpu/spv.s: each module as words in .rodata,
spv_<name> .. spv_<name>_end. The output is committed, so building the
helper needs no shader compiler.

    python3 tools/genspv.py
"""
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GPU = os.path.join(HERE, '..', 'src', 'gpu')
SHADERS = ['pt', 'raster', 'ptg']   # ptg: pt.comp with shader graphs (-DGRAPHS)


def main():
    out = ['# generated by tools/genspv.py from src/gpu/*.comp - do not edit',
           '.section .rodata', '.align 4']
    with tempfile.TemporaryDirectory() as tmp:
        for name in SHADERS:
            spv = os.path.join(tmp, name + '.spv')
            src, defs = (name, []) if name != 'ptg' else ('pt', ['-DGRAPHS'])
            subprocess.run(['glslc', '-O', '--target-env=vulkan1.1'] + defs + ['-o', spv,
                            os.path.join(GPU, src + '.comp')], check=True)
            data = open(spv, 'rb').read()
            words = struct.unpack('<%dI' % (len(data) // 4), data)
            out.append('.globl spv_%s\n.globl spv_%s_end' % (name, name))
            out.append('spv_%s:' % name)
            for i in range(0, len(words), 8):
                out.append('    .long ' + ', '.join('0x%08x' % w for w in words[i:i + 8]))
            out.append('spv_%s_end:' % name)
            print('%s: %d bytes of SPIR-V' % (name, len(data)))
    with open(os.path.join(GPU, 'spv.s'), 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    sys.exit(main())
