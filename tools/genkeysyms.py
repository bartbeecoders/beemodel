#!/usr/bin/env python3
# Dev-time helper only (NOT needed to build): generates src/keysyms.inc, the
# keysym-name -> Unicode table used by the XKB keymap parser (keyboard.s).
# Covers Latin-1 (keysym == code point), dead keys and a few common extras.
# Format per entry: .byte len, .ascii name, .long value ; terminated by .byte 0
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/include/X11/keysymdef.h'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/keysyms.inc'
syms = {}
for line in open(src, encoding='latin-1'):
    m = re.match(r'#define XK_(\w+)\s+0x([0-9a-fA-F]+)', line)
    if not m: continue
    name, val = m.group(1), int(m.group(2), 16)
    if 0x20 <= val <= 0xff and not (len(name) == 1 and name.isalnum()):
        syms.setdefault(name, val)              # Latin-1: keysym == code point
DEAD = ['grave', 'acute', 'circumflex', 'tilde', 'diaeresis', 'abovering', 'caron', 'cedilla']
for i, d in enumerate(DEAD, 1):
    syms['dead_' + d] = 0x80000000 | i         # dead keys: flag | kind
syms.update({'EuroSign': 0x20ac, 'dead_perispomeni': 0x80000004, 'KP_Space': 0x20,
             'KP_Add': 0x2b, 'KP_Subtract': 0x2d, 'KP_Multiply': 0x2a, 'KP_Divide': 0x2f,
             'KP_Decimal': 0x2e, 'KP_Separator': 0x2c, 'KP_Equal': 0x3d})
for d in range(10): syms[f'KP_{d}'] = 0x30 + d
lines = ['# Generated by tools/genkeysyms.py - keysym name -> Unicode (dead keys: 0x8000000k)',
         'keysym_table:']
for name in sorted(syms):
    lines.append(f'    .byte {len(name)}\n    .ascii "{name}"\n    .long 0x{syms[name]:x}')
lines.append('    .byte 0')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(syms)} keysyms -> {out}')
