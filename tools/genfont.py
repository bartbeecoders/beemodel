#!/usr/bin/env python3
# Dev-time helper only (NOT needed to build): converts a PSF2 console font into
# src/font.inc, an 8x16 1-bit glyph table for ASCII 32..126 that is assembled
# straight into the binary.
import gzip, struct, sys
path = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/kbd/consolefonts/default8x16.psfu.gz'
d = gzip.open(path).read()
magic, ver, hsz, flags, n, bpg, h, w = struct.unpack('<8I', d[:32])
assert magic == 0x864ab572 and w == 8 and h == 16
glyphs = d[hsz:hsz + n * bpg]
cmap = {}
if flags & 1:
    tab = d[hsz + n * bpg:]
    gi, i = 0, 0
    while gi < n and i < len(tab):
        j = tab.index(b'\xff', i)
        entry = tab[i:j]
        k = entry.find(b'\xfe')
        if k >= 0: entry = entry[:k]
        for ch in entry.decode('utf-8', 'ignore'):
            cmap.setdefault(ord(ch), gi)
        gi += 1; i = j + 1
out = ['# Generated by tools/genfont.py from ' + path.split('/')[-1],
       '# 95 glyphs (ASCII 32..126), 16 rows each, MSB = leftmost pixel', 'font_8x16:']
for c in range(32, 127):
    g = cmap.get(c, c)
    rows = glyphs[g * bpg:(g + 1) * bpg]
    out.append('    .byte ' + ','.join('0x%02x' % b for b in rows) + '   # ' + repr(chr(c)))
open(sys.argv[2] if len(sys.argv) > 2 else 'src/font.inc', 'w').write('\n'.join(out) + '\n')
