#!/usr/bin/env bash
# Build BeeModel: assemble with GNU as, link statically with ld. No libraries.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build
MODE="${1:-release}"
VERSION="$(tr -d '[:space:]' < VERSION)"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]] || { echo "bad VERSION: $VERSION" >&2; exit 1; }
printf '# generated by build.sh from VERSION\ns_version: .asciz "%s"\n' "$VERSION" > build/version.inc
ASFLAGS=(--64 -I src -I build)
[[ "$MODE" == "debug" ]] && ASFLAGS+=(-g)

as "${ASFLAGS[@]}" -o build/beemodel.o src/main.s
if [[ "$MODE" == "debug" ]]; then
    ld -static -nostdlib -o build/beemodel build/beemodel.o
else
    # -s strip symbols, -n no page-aligned sections, --gc-sections drop unused
    ld -static -nostdlib -s --gc-sections --build-id=none -z noexecstack \
       -o build/beemodel build/beemodel.o
fi
echo "built build/beemodel v$VERSION ($(stat -c %s build/beemodel) bytes, mode: $MODE)"
