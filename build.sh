#!/usr/bin/env bash
# Build BeeModel: assemble with GNU as, link statically with ld. No libraries.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p build
MODE="${1:-release}"
VERSION="$(tr -d '[:space:]' < VERSION)"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]] || { echo "bad VERSION: $VERSION" >&2; exit 1; }
printf '# generated by build.sh from VERSION\n.globl s_version\ns_version: .asciz "%s"\n' "$VERSION" > build/version.inc
ASFLAGS=(--64 -I src -I build)
[[ "$MODE" == "debug" ]] && ASFLAGS+=(-g)

# Every src/*.s is its own module (translation unit); main.s goes first so
# _start leads the text segment.
OBJS=()
for src in src/main.s $(ls src/*.s | grep -v '^src/main.s$'); do
    obj="build/obj/$(basename "${src%.s}").o"
    mkdir -p build/obj
    as "${ASFLAGS[@]}" -o "$obj" "$src"
    OBJS+=("$obj")
done
if [[ "$MODE" == "debug" ]]; then
    ld -static -nostdlib -o build/beemodel "${OBJS[@]}"
else
    # -s strip symbols, --gc-sections drop unused sections
    ld -static -nostdlib -s --gc-sections --build-id=none -z noexecstack \
       -o build/beemodel "${OBJS[@]}"
fi
echo "built build/beemodel v$VERSION ($(stat -c %s build/beemodel) bytes, mode: $MODE)"
